#!/usr/bin/env bash
# Regenerate the vendored Gentelella CSS used by the DumpAnalyzer dashboard.
#
# Gentelella (https://github.com/ColorlibHQ/gentelella) is an MIT-licensed
# admin template. The dashboard uses its compiled design system (tokens,
# layout shell, cards, tables, forms, badges/status) as the base layer;
# src/ui/app.css is the thin DumpAnalyzer-specific layer on top.
#
# The template is pinned by commit so the vendored artifact is reproducible
# and reviewable. Re-run this script only when intentionally upgrading the
# template; it rewrites src/ui/gentelella.css and src/ui/GENTELELLA-LICENSE.txt.
# The generated files are committed, so a normal build/test run never needs
# this script.
#
# Requirements: git, node/npm (network access to github.com and the npm
# registry).
set -euo pipefail

GENTELELLA_REPO="${GENTELELLA_REPO:-https://github.com/ColorlibHQ/gentelella.git}"
GENTELELLA_REF="${GENTELELLA_REF:-02936f9003baa8473aa39dadd4ce23b679961d53}" # v4.2.0
SASS_VERSION="${SASS_VERSION:-1.107.0}"

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ui_dir="$repo_root/src/ui"
out_css="$ui_dir/gentelella.css"
out_license="$ui_dir/GENTELELLA-LICENSE.txt"

if ! command -v git >/dev/null; then
  echo "vendor-gentelella: git is required" >&2
  exit 1
fi
if ! command -v npx >/dev/null; then
  echo "vendor-gentelella: npx (Node.js) is required" >&2
  exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

echo "vendor-gentelella: fetching $GENTELELLA_REPO at $GENTELELLA_REF"
git -C "$work" init --quiet
git -C "$work" remote add origin "$GENTELELLA_REPO"
git -C "$work" fetch --quiet --depth 1 origin "$GENTELELLA_REF"
git -C "$work" checkout --quiet FETCH_HEAD

version="$(sed -n 's/^  "version": "\(.*\)",$/\1/p' "$work/package.json" | head -n1)"
echo "vendor-gentelella: templates package version ${version:-unknown}"

echo "vendor-gentelella: compiling src/scss/v4/main.scss"
npx --yes "sass@$SASS_VERSION" --no-source-map --style=compressed \
  "$work/src/scss/v4/main.scss" "$work/gentelella.min.css"

{
  cat <<'HEADER'
/*! Gentelella v4 admin template (https://github.com/ColorlibHQ/gentelella)
 * Copyright (c) Colorlib / Aigars Silkalns. MIT license; see GENTELELLA-LICENSE.txt.
HEADER
  printf ' * Vendored build: full main.scss, pinned commit %s (v%s).\n' "$GENTELELLA_REF" "${version:-unknown}"
  cat <<'HEADER'
 * Generated by tools/vendor-gentelella.sh - do not edit by hand.
 */
HEADER
  cat "$work/gentelella.min.css"
} > "$out_css"

cp "$work/LICENSE.txt" "$out_license"

echo "vendor-gentelella: wrote $out_css ($(wc -c < "$out_css") bytes)"
echo "vendor-gentelella: wrote $out_license"
